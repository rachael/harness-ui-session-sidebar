"""Claude Code adapter: generated data stays in step with its shared source, and the
adapter carries nothing private.

`python3 tests/test_claude_adapter.py --write` regenerates the adapter's copies:
`assets/sprites.json` -> `adapters/claude-code/hooks/claudes.ts` and
`contracts/fixtures/*.json` -> `adapters/claude-code/tests/fixtures.ts`. The plugin
runtime cannot import JSON, so it carries these generated TypeScript copies.
"""
import json
from pathlib import Path
import re
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
ADAPTER = ROOT/'adapters'/'claude-code'
SPRITES = ROOT/'assets'/'sprites.json'
FIXTURES = ROOT/'contracts'/'fixtures'

HEADER = '// Generated by tests/test_claude_adapter.py --write from {source}; do not edit.\n'


def sprites_ts():
    data = json.loads(SPRITES.read_text())
    return (HEADER.format(source='assets/sprites.json')
            + "// Little Claudes for the pane's corner, one picked at random per session. Every\n"
            + '// frame is 4 rows, so a swap never moves the pane. The mod implements the actions.\n'
            + "export type ClaudeAction = { kind: 'toast'; text: string } | { kind: 'animate' } | { kind: 'next' } | { kind: 'recap' }\n"
            + 'export type LittleClaude = { name: string; frames: string[][]; color: string; action: ClaudeAction }\n\n'
            + 'export const CLAUDES: LittleClaude[] = '
            + json.dumps(data['sprites'], indent=1, ensure_ascii=False) + '\n')


def fixtures_ts():
    out = [HEADER.format(source='contracts/fixtures')]
    for name in ('overview', 'sections', 'expected'):
        value = json.loads((FIXTURES/(name+'.json')).read_text())
        out.append(f'export const {name.upper()}: any = ' + json.dumps(value, indent=2, ensure_ascii=False) + '\n')
    return '\n'.join(out)


# The plugin's bundled state runtime: exact copies of the shared modules it needs.
RUNTIME_MODULES = ('__init__.py', 'bootstrap.py', 'core.py', 'surface.py', 'statusline.py', 'claude_statusline.py', 'sessions.py', 'terminals.py', 'sidebar.py')


def runtime_copy(name):
    return lambda: (ROOT/'src'/'codex_ui_mods'/name).read_text()


GENERATED = {
    ADAPTER/'hooks'/'claudes.ts': sprites_ts,
    ADAPTER/'tests'/'fixtures.ts': fixtures_ts,
    **{ADAPTER/'runtime'/'codex_ui_mods'/name: runtime_copy(name) for name in RUNTIME_MODULES},
}

# Generic checks suitable for redistribution. Project-specific publication
# checks belong to the publisher's private release process, not this package.
PRIVATE = re.compile(
    r'/Users/|/home/(?!example|test)|(?:sk-ant-|ghp_|github_pat_)[A-Za-z0-9_-]{16,}|'
    r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}',
    re.IGNORECASE)
# The public repository's own address is meant to be there.
PUBLIC = re.compile(r'(?:github\.com/|githubusercontent\.com/|[\s"\'])rachael/harness-ui-mods')


class ClaudeAdapterTests(unittest.TestCase):
    def test_generated_copies_match_their_sources(self):
        for path, render in GENERATED.items():
            with self.subTest(path=path.relative_to(ROOT)):
                self.assertEqual(path.read_text(), render(), 'run tests/test_claude_adapter.py --write')

    def test_sprites_keep_fixed_geometry_and_generic_text(self):
        sprites = json.loads(SPRITES.read_text())['sprites']
        self.assertTrue(sprites)
        for sprite in sprites:
            self.assertIn(sprite['action']['kind'], {'toast', 'animate', 'next', 'recap'})
            widths = {len(row) for frame in sprite['frames'] for row in frame}
            for frame in sprite['frames']:
                self.assertEqual(len(frame), 4, sprite['name'])
            self.assertEqual(len(widths), 1, sprite['name'])

    def test_idle_waver_has_no_unattached_speech_stem(self):
        sprites = json.loads(SPRITES.read_text())['sprites']
        waver = next(sprite for sprite in sprites if sprite['name'] == 'a-waver')
        self.assertNotIn('/', ''.join(waver['frames'][0]))
        self.assertEqual(waver['action']['kind'], 'toast')

    def test_fixtures_are_consistent(self):
        record = json.loads((FIXTURES/'overview.json').read_text())
        expected = json.loads((FIXTURES/'expected.json').read_text())
        surfaced = {entry['id']: entry for entry in record['surfaced']}
        for identity in expected['badges']:
            self.assertTrue(surfaced[identity]['verified'])
            self.assertNotEqual(surfaced[identity]['status'], 'resolved')
        self.assertFalse(set(expected['visible']) & set(expected['hidden']))

    def test_manifest_names_the_plugin_and_its_feature_switches(self):
        manifest = json.loads((ADAPTER/'manifest.json').read_text())
        plugin = json.loads((ADAPTER/'.claude-plugin'/'plugin.json').read_text())
        self.assertEqual(manifest['plugin'], plugin['name'])
        self.assertEqual(manifest['version'], plugin['version'])
        for feature in manifest['features']:
            option = plugin['userConfig'][feature['config_key']]
            self.assertEqual(option['type'], 'boolean')
            self.assertEqual(option['default'], feature['default'])
        for name in manifest['files']:
            self.assertTrue((ADAPTER/name).is_file(), name)

    def test_adapter_carries_nothing_private(self):
        for path in sorted(ADAPTER.rglob('*')):
            if not path.is_file() or '.claude-plugin/types' in path.as_posix() or '__pycache__' in path.parts:
                continue
            text = path.read_text(errors='replace')
            for number, line in enumerate(text.splitlines(), 1):
                with self.subTest(file=path.relative_to(ROOT).as_posix(), line=number):
                    self.assertIsNone(PRIVATE.search(PUBLIC.sub('', line)), line.strip()[:120])

    def test_adapter_runs_only_generic_commands(self):
        source = '\n'.join(p.read_text() for p in (ADAPTER/'hooks').glob('*.ts*'))
        commands = set(re.findall(r"process\.run\(\s*\[\s*'([^']+)'", source))
        self.assertLessEqual(commands, {'git', 'osascript'})
        self.assertIn("$.env.get('HARNESS_UI_COMMAND')", source)
        self.assertIn("['python3', `${$.plugin.root}/runtime/harness-ui-state.py`]", source)


if __name__ == '__main__':
    if '--write' in sys.argv:
        for path, render in GENERATED.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(render())
            print('wrote', path.relative_to(ROOT))
    else:
        unittest.main()
